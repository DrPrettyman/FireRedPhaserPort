// sound/MPlayDef.s
const TUNE = 0xc8, GOTO = 0xb2, VOICE = 0xbd, VOL = 0xbe, XCMD = 0xcd, PAN = 0xbf, TIE = 0xcf, EOT = 0xce;
const FINE = 0xb1, xRELE = 0x07, xWAIT = 0x0c;

/** gPokemonCrySongTemplate (m4a_tables.c:259) as a fresh PokemonCrySong. The tone (`voicegroup000` in the C) is
 *  null: SetPokemonCryTone always sets it. The GOTO's target is `cont`'s offset in `data` (the C stores an
 *  address there, set by SetPokemonCryTone). */
export function pokemonCrySongTemplate(): PokemonCrySong {
  const data = new Uint8Array(CRY_SONG_SIZE);
  data.set(
    [
      TUNE, C_V, // part 0, TUNE value
      GOTO, 0, 0, 0, 0, // GOTO target address (and the u32's alignment gap)
    ],
    CRY_SONG_PART0,
  );
  data[CRY_SONG_GOTO_TARGET] = CRY_SONG_CONT;
  data.set(
    [
      TUNE, C_V + 16, // part 1, TUNE value
      VOICE, 0, // part 0 jumps here with GOTO
      VOL, 127, // volume
      XCMD, 0x0d, 0, 0, 0, 0, // unk value (the u32 at 0x20)
      XCMD, xRELE, 0, // release
      PAN, C_V, // PAN value
      TIE, 60, 127, // TIE key (default is Cn3), TIE velocity
      XCMD, xWAIT, 60, 0, // frames to wait (the u16 at 0x2E)
      EOT, FINE, // end
    ],
    CRY_SONG_PART1,
  );
  if (data[CRY_SONG_LENGTH] !== 60) throw new Error('pokemonCrySongTemplate: layout');
  return { trackCount: 1, blockCount: 0, priority: 255, reverb: 0, tone: null, data };
}
